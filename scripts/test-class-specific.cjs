const {PGlite}=require('@electric-sql/pglite');
const {readFileSync}=require('fs');
const assert=require('node:assert/strict');
(async()=>{
 const db=new PGlite();
 await db.exec(`create role anon; create role authenticated; create role service_role;
 create schema auth; create table auth.users(id uuid primary key,raw_user_meta_data jsonb default '{}');
 create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 create table user_profiles(id uuid primary key,username text);`);
 for(const file of ['cohorts_schema.sql','teacher_workspace.sql','subject_course_enrollment.sql','class_specific_enrollment.sql'])await db.exec(readFileSync('supabase/'+file,'utf8'));
 // The upgrade is safe to rerun.
 await db.exec(readFileSync('supabase/class_specific_enrollment.sql','utf8'));
 await db.exec(`create schema storage; create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 create table storage.objects(bucket_id text,name text); alter table storage.objects enable row level security;
 create function storage.foldername(text) returns text[] language sql as $$ select string_to_array($1,'/') $$;`);
 await db.exec(readFileSync('supabase/class_thumbnails.sql','utf8'));
 await db.exec(readFileSync('supabase/class_thumbnails.sql','utf8'));
 const ids=[1,2,3].map(n=>`10000000-0000-4000-8000-00000000000${n}`);
 for(const id of ids)await db.query('insert into auth.users(id) values($1)',[id]);
 for(const id of ids.slice(0,2))await db.query("insert into tutors(id,display_name,status) values($1,'Teacher','active')",[id]);
 await db.exec("update subjects set enrollment_price=5000 where id='physics'");
 const classes=[];
 for(const teacher of [ids[0],ids[0],ids[1]])classes.push((await db.query("insert into cohorts(tutor_id,subject_id,title,start_date,published) values($1,'physics','Physics',current_date,true) returning id",[teacher])).rows[0].id);
 await db.query("select set_config('request.jwt.claim.sub',$1,false)",[ids[2]]);
 const path=ids[0]+'/10000000-0000-4000-8000-000000000009.jpg';
 await db.query("insert into storage.objects values('class-thumbnails',$1)",[path]);
 await db.query("insert into class_revisions(cohort_id,body) values($1,$2)",[classes[0],{thumbnail_path:path}]);
 assert.equal((await db.query('select thumbnail_path from cohorts where id=$1',[classes[0]])).rows[0].thumbnail_path,null);
 await db.query("update class_revisions set state='published' where cohort_id=$1",[classes[0]]);
 assert.equal((await db.query('select thumbnail_path from cohorts where id=$1',[classes[0]])).rows[0].thumbnail_path,path);
 await assert.rejects(()=>db.query('update class_revisions set body=$1 where cohort_id=$2',[{thumbnail_path:ids[1]+'/10000000-0000-4000-8000-000000000009.jpg'},classes[0]]),/valid class thumbnail/);
 await db.query("update class_revisions set body='{}',state='draft' where cohort_id=$1",[classes[0]]);
 assert.equal((await db.query('select thumbnail_path from cohorts where id=$1',[classes[0]])).rows[0].thumbnail_path,path);
 await db.query("update class_revisions set state='published' where cohort_id=$1",[classes[0]]);
 assert.equal((await db.query('select thumbnail_path from cohorts where id=$1',[classes[0]])).rows[0].thumbnail_path,null);
 const order=async id=>(await db.query('select class_order_create($1) as o',[id])).rows[0].o;
 const a=await order(classes[0]), b=await order(classes[1]), c=await order(classes[2]);
 assert.notEqual(a.reference,b.reference);assert.notEqual(a.reference,c.reference);
 assert.equal((await order(classes[0])).reference,a.reference);
 const settle=()=>db.query("select class_order_settle($1,$2,'NGN',now(),$3)",[a.reference,a.amount_kobo,ids[2]]);
 await settle();await settle();
 for(let i=0;i<3;i++)assert.equal((await db.query('select workspace_enrolled($1) as allowed',[classes[i]])).rows[0].allowed,i===0);
 const earnings=(await db.query('select * from teacher_earnings')).rows;
 assert.equal(earnings.length,1);assert.equal(earnings[0].tutor_id,ids[0]);assert.equal(Number(earnings[0].teacher_kobo),350000);
 assert.equal((await order(classes[0])).enrolled,true);
 await db.query("insert into cohorts(tutor_id,subject_id,title,start_date,published) values($1,'physics','New class',current_date,true)",[ids[0]]);
 assert.equal((await db.query('select count(*)::int as n from enrollments')).rows[0].n,1);
 await db.close();console.log('PASS: class isolation across same/different teachers, checkout reuse, idempotent settlement, 70% earnings and no future class inheritance.');
})().catch(e=>{console.error(e);process.exitCode=1;});
